/**
 * Размеры фото карточки (SP-15 срез 3b) — чистая арифметика, без DOM.
 *
 * Пересжатия кадра в клиенте НЕТ и не будет: D-070 отменён, §7 SP-15 — «оригинал
 * едет документом и НЕ масштабируется ни на клиенте, ни на сервере» (что снял
 * мастер, то и лежит; зум показывает оригинал). Поэтому единственное, что клиент
 * обязан сделать с размером — честно предупредить о «крупном» кадре: Bot API
 * `getFile` отдаёт ≤20 МБ, а именно столько отдаёт СЕРВЕРНЫЙ ПРОКСИ (TWA/браузер
 * и чужие публичные карточки).
 *
 * SP-15 срез 5 (D-071): в Desktop байты тянет СВОЯ TDLib, поэтому лимита 20 МБ
 * там больше нет — порог остаётся ровно для честной подсказки «в веб будет превью».
 *
 * Форматирование байт здесь своё НЕ заводится: канон — `formatBytes` из `./format`
 * (одно место форматирования, расширения ASCII — i18n «хрома» не нужна).
 */

/** Порог «крупного» фото — 20 МБ (потолок Bot API `getFile` для веб-ветки). */
export const MEDIA_LARGE_BYTES = 20 * 1024 * 1024;

export type MediaSizeNotice = "ok" | "large";

/** Предупреждение о размере: `large` — показать в UI, что в веб будет превью. */
export function mediaSizeNotice(sizeBytes: number): MediaSizeNotice {
  if (!Number.isFinite(sizeBytes) || sizeBytes <= 0) return "ok";
  return sizeBytes > MEDIA_LARGE_BYTES ? "large" : "ok";
}
