/**
 * Когда перечитывать список личного кабинета (BUG-CABINET-STALE-001).
 *
 * Список кабинета (`SearchPage`, вкладка «Пошук» в личном режиме) приходит
 * ОДНИМ GET `/api/v1/search/personal` и живёт в DOM до следующего действия
 * пользователя. Пока список не помечен устаревшим, открытие вкладки его НЕ
 * перечитывает: иначе каждое переключение вкладок перерисовывало бы выдачу и
 * сбрасывало карточку, закреплённую переходом из чата (`CardJump`).
 *
 * Решение — чистая функция, чтобы правило жило в одном месте и проверялось
 * тестом без DOM (`tests/personal-cabinet-refresh.test.ts`).
 */

/** Режим клиента (`vaultMode`): личный кабинет или публичное поле. */
export type CabinetScope = "public" | "personal";

export interface CabinetRefreshInput {
  /** Текущий режим клиента. */
  scope: CabinetScope | string;
  /** Вкладка, которая становится активной (`data-tab`). */
  tab: string;
  /** Список кабинета помечен устаревшим (была личная загрузка/приём файла). */
  stale: boolean;
}

/**
 * Нужно ли перечитать список кабинета.
 *
 * Только личный режим (публичный каталог живёт по своим правилам — A3) и
 * только «устаревший» список, и только при открытии вкладки «Пошук».
 */
export function shouldRefreshCabinet(input: CabinetRefreshInput): boolean {
  return input.stale === true && input.scope === "personal" && input.tab === "search";
}
